"""Refresh compiled validator helpers from the generator's checked-in output.

Run after regenerating the existing fixtures, then run moon fmt. CI checks the
result with git diff, so value semantics stay tied to the code generator.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
GROUPS = {
    "fixtures/ieee754/generated.mbt": ["kind_name", "actual_type", "matches_type", "binary16_float_compatible", "ieee754_float_compatible"],
    "fixtures/contains/generated.mbt": ["symbols_equal", "annotations_equal", "values_equal", "sequences_equal", "structs_equal"],
    "fixtures/constraints/generated.mbt": ["valid_values_equal", "has_annotation", "is_minimum", "is_maximum", "valid_values_match", "range_contains", "compare_values", "power", "number_parts", "float_parts", "compare_decimal_parts", "is_leap_year", "days_in_month", "timestamp_seconds", "compare_timestamps"],
    "fixtures/precision/generated.mbt": ["decimal_precision", "decimal_exponent"],
    "fixtures/timestamps/generated.mbt": ["timestamp_precision", "timestamp_offset_is_allowed"],
    "fixtures/annotations/generated.mbt": ["container_length", "codepoint_length", "utf8_byte_length", "annotations_match"],
    "fixtures/regex/generated.mbt": ["regex_matches"],
}


def main():
    result = ["// Generated by scripts/sync_validator_support.py; do not edit.\n"
              "// Source: shared helpers emitted into the existing fixtures.\n"]
    for filename, names in GROUPS.items():
        blocks = re.split(r"(?m)^///\|\s*$", (ROOT / filename).read_text(encoding="utf-8"))
        for name in names:
            prefix = "fn ion_schema_codegen_" + name + "("
            matches = [block.strip() for block in blocks if block.strip().startswith(prefix)]
            if len(matches) != 1:
                raise RuntimeError(f"{filename}: expected exactly one helper {name}")
            source = matches[0].replace("ion_schema_codegen_", "validator_support_").replace("@ion_model", "@model")
            result.append("///|\n" + source + "\n")
    (ROOT / "validator_support.mbt").write_text("\n".join(result), encoding="utf-8")


if __name__ == "__main__":
    main()
